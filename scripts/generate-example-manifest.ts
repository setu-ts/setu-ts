/* eslint-disable no-console -- the manifest generator reports the file it writes. */
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import * as prettier from 'prettier';
import { EXAMPLES } from '../packages/cli/src/examples/catalog.ts';

/** Builds the manifest from tracked app files, retaining manifests for their standalone rewrite. */
export async function collectExampleManifest(
  root: string,
): Promise<Record<string, { files: string[]; smokeHelper: boolean }>> {
  const { stdout } = await promisify(execFile)('git', ['ls-files', '-z', '--', 'apps/'], {
    cwd: root,
  });
  const tracked = stdout.split('\0').filter(Boolean);
  return Object.fromEntries(
    EXAMPLES.map((name) => {
      const prefix = `apps/${name}/`;
      const files = tracked
        .filter((file) => file.startsWith(prefix))
        .map((file) => file.slice(prefix.length))
        .filter((file) => !/(^|\/)(node_modules|dist|build|\.tmp)(\/|$)/.test(file))
        .sort();
      const smokeHelper = files
        .filter((file) => /\.[cm]?[jt]sx?$/.test(file))
        .some((file) =>
          readFileSync(resolve(root, prefix, file), 'utf8').includes('../smoke-helpers.ts'),
        );
      return [name, { files, smokeHelper }];
    }),
  );
}

/** Renders the committed TypeScript manifest with the repository formatter. */
export async function generateExampleManifest(root: string): Promise<string> {
  return prettier.format(
    `/** Generated by pnpm run examples:manifest; do not edit by hand. */
import type { ExampleName } from './catalog.ts';
/** Tracked files fetched for each offered example; package.json and tsconfig.json are rewritten. */
export const EXAMPLE_MANIFEST: Readonly<Record<ExampleName, { readonly files: readonly string[]; readonly smokeHelper: boolean }>> = ${JSON.stringify(await collectExampleManifest(root))};`,
    { ...(await prettier.resolveConfig(resolve(root, 'package.json'))), parser: 'typescript' },
  );
}

/** Writes the generated manifest; callable without executing at import time. */
export async function writeExampleManifest(root: string): Promise<void> {
  writeFileSync(
    resolve(root, 'packages/cli/src/examples/manifest.ts'),
    await generateExampleManifest(root),
  );
}

/** Runs the executable path, with an explicit switch so both entry modes are testable. */
export async function runExampleManifestMain(
  enabled = import.meta.main,
  root = resolve(import.meta.dirname, '..'),
  log: (message: string) => void = console.log,
): Promise<void> {
  if (!enabled) return;
  await writeExampleManifest(root);
  log('Wrote packages/cli/src/examples/manifest.ts');
}

await runExampleManifestMain();
