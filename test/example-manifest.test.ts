import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, posix } from 'node:path';
import ts from 'typescript';
import { describe, expect, it } from 'vitest';
import {
  collectExampleManifest,
  generateExampleManifest,
  writeExampleManifest,
  runExampleManifestMain,
} from '../scripts/generate-example-manifest.ts';
import { EXAMPLES } from '../packages/cli/src/examples/catalog.ts';
import { run } from '../scripts/lib/run.ts';
import { tempDir } from './node-helpers.ts';

describe('example manifest', () => {
  it('matches regeneration and refuses repository-dependent imports in every offered file', async () => {
    expect(await generateExampleManifest(resolve('.'))).toBe(
      await readFile('packages/cli/src/examples/manifest.ts', 'utf8'),
    );
    const manifest = await collectExampleManifest(resolve('.'));
    const failures: string[] = [];
    for (const [app, entry] of Object.entries(manifest))
      for (const file of entry.files) {
        if (!/\.[cm]?[jt]sx?$/.test(file)) continue;
        const path = `apps/${app}/${file}`;
        const source = await readFile(path, 'utf8');
        for (const imported of ts.preProcessFile(source, true, true).importedFiles) {
          const specifier = imported.fileName;
          if (!specifier.startsWith('.')) continue;
          const target = posix.normalize(posix.join(posix.dirname(path), specifier));
          if (!target.startsWith(`apps/${app}/`) && target !== 'apps/smoke-helpers.ts')
            failures.push(`${path}: ${specifier}`);
        }
      }
    expect(failures).toEqual([]);
  });
  it('excludes output directories, sorts tracked files, and writes exactly the generated bytes', async () => {
    const root = await tempDir({ prefix: 'example-manifest-' });
    expect((await run('git', ['init', root])).code).toBe(0);
    for (const app of EXAMPLES) {
      await mkdir(`${root}/apps/${app}/dist`, { recursive: true });
      await writeFile(
        `${root}/apps/${app}/main.ts`,
        app === 'minimal' ? "import '../smoke-helpers.ts';" : 'export {};',
      );
      await writeFile(`${root}/apps/${app}/package.json`, '{}');
      await writeFile(`${root}/apps/${app}/dist/output.js`, 'ignored');
    }
    await writeFile(`${root}/apps/minimal/logo.bin`, new Uint8Array([0xff, 0xfe, 0x00]));
    expect((await run('git', ['add', '.'], { cwd: root })).code).toBe(0);
    const manifest = await collectExampleManifest(root);
    expect(manifest['minimal']).toEqual({
      files: ['logo.bin', 'main.ts', 'package.json'],
      binary: ['logo.bin'],
      smokeHelper: true,
    });
    expect(manifest['rest-api']?.binary).toEqual([]);
    expect(manifest['rest-api']?.smokeHelper).toBe(false);
    await mkdir(`${root}/packages/cli/src/examples`, { recursive: true });
    await writeExampleManifest(root);
    expect(await readFile(`${root}/packages/cli/src/examples/manifest.ts`, 'utf8')).toBe(
      await generateExampleManifest(root),
    );
    const messages: string[] = [];
    await runExampleManifestMain(true, root, (message) => messages.push(message));
    expect(messages).toEqual(['Wrote packages/cli/src/examples/manifest.ts']);
    await runExampleManifestMain(false, `${root}/does-not-exist`);
  });
});
