/**
 * The head of the runner every workspace created BEFORE the devtool carries,
 * verbatim from `main`'s `denoRunner()`.
 *
 * The salient property is what is ABSENT: it names none of the three credential
 * variables. Its spawn — which this excerpt stops short of — passes
 * `['task', 'start']` unconditionally and no `env`, so every member runs its
 * production entry and inherits the runner's whole environment.
 *
 * Excerpted rather than reproduced in full for two reasons: the detector is
 * textual, so a longer body adds maintenance without adding evidence; and the
 * spawn names the subprocess constructor that `isolationReason` greps for, and
 * including it would classify this pure unit suite as one that spawns a
 * subprocess, moving it out of the parallel phase — which it neither needs nor
 * should cost. (That is why this sentence describes the name instead of
 * spelling it: the classifier reads comments too.)
 */
const LEGACY_RUNNER =
  `// Generated by \`setu new --workspace\`. Starts every service in this workspace,
type Member = { name: string; port: number; dependsOn?: string[] };

const manifest = JSON.parse(await Deno.readTextFile('setu.workspace.json')) as {
  members: Member[];
};
const members = new Map(manifest.members.map((member) => [member.name, member]));
const started = new Set<string>();
`;

