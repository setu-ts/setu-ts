/**
 * The runner check, on both entry points that can meet a workspace created
 * before the devtool existed.
 *
 * The defect this pins shipped: the command widened the root `dev` TASK in
 * place from its pre-devtool value — so it already knew it might be operating
 * on such a workspace — and left the SCRIPT that task runs untouched. Nothing
 * regenerates `scripts/dev.ts`: it is written once by `setu new --workspace`
 * and appears in no `managedFiles` list. So `devtool enable` reported success,
 * recorded a port, wrote the entry, and `deno task dev` went on spawning
 * `main.ts` for every member. The connector never bound, and the same stale
 * runner passes no per-child `env`, so every sibling would have inherited the
 * credential pair M98b forbids them to hold.
 */
describe('the workspace runner must honor the credential contract', () => {
  it('refuses a pre-devtool runner by name and writes nothing', async () => {
    const h = workspaceHarness({
      ...workspaceSeed([{ name: 'orders', port: 3000 }]),
      '/ws/scripts/dev.ts': LEGACY_RUNNER,
    });
    expect(await h.run(['enable', 'orders'])).toBe(1);
    const message = h.err.text();
    expect(message).toContain('scripts/dev.ts predates the devtool');
    // The remedy is named, and so is every variable a hand-port must read.
    expect(message).toContain('Delete scripts/dev.ts and run this again');
    for (const name of DEVTOOL_ENV_NAMES) expect(message).toContain(name);
    // Nothing at all: no port recorded, no entry, no widened root task.
    expect(h.fs.writes).toEqual([]);
  });

  it('refuses the same runner on `generate app --devtool`, creating no member', async () => {
    const fs = createFakeFs({
      ...workspaceSeed([{ name: 'orders', port: 3000 }]),
      '/ws/scripts/dev.ts': LEGACY_RUNNER,
    });
    const err = createRecorder();
    const code = await runAppCommand(parseArgs(['app', 'billing', '--devtool']), {
      fs,
      dir: '/ws',
      log: createRecorder().sink,
      error: err.sink,
    });
    expect(code).toBe(1);
    expect(err.text()).toContain('scripts/dev.ts predates the devtool');
    expect(fs.writes).toEqual([]);
  });

  it('proceeds against a runner that already reads the three names', async () => {
    const h = workspaceHarness({
      ...workspaceSeed([{ name: 'orders', port: 3000 }]),
      '/ws/scripts/dev.ts': devtoolDevRunner().contents,
    });
    expect(await h.run(['enable', 'orders']), h.err.text()).toBe(0);
    // A runner that honors the contract is left exactly as it was found: this
    // command never rewrites a file that is the developer's.
    expect(h.fs.writes).not.toContain('/ws/scripts/dev.ts');
  });

  it('creates the runner when the workspace has none, rather than refusing', async () => {
    const h = workspaceHarness(workspaceSeed([{ name: 'orders', port: 3000 }]));
    expect(await h.run(['enable', 'orders']), h.err.text()).toBe(0);
    const written = h.fs.read('/ws/scripts/dev.ts');
    expect(written).toBe(devtoolDevRunner().contents);
    for (const name of DEVTOOL_ENV_NAMES) expect(written).toContain(name);
  });
});

