describe('managed files with an ownership marker', () => {
  const path = '/app/test/support/pages.ts';
  const marker = '// Regenerated by setu g module; do not edit this file.';
  const plan = [{ path, contents: `${marker}\nnew`, managed: true, ownedMarker: marker }];

  it('writes an absent file and rewrites one that still carries the marker', async () => {
    const fs = createFakeFs();
    expect(await findExisting(fs, plan)).toEqual([]);
    await fs.writeFile(path, new TextEncoder().encode(`${marker}\nold`));
    expect(await findExisting(fs, plan)).toEqual([]);
    expect(await writeFiles(fs, plan, { root: '/app' })).toEqual([{ path, outcome: 'updated' }]);
    expect(fs.read(path)).toBe(`${marker}\nnew`);
  });

  it("reports the developer's own file, and one it cannot read as text, as collisions", async () => {
    for (const bytes of [
      new TextEncoder().encode('export const mine = 1;\n'),
      new Uint8Array([255, 0, 13, 10]),
    ]) {
      const fs = createFakeFs();
      await fs.writeFile(path, bytes);
      expect(await findExisting(fs, plan)).toEqual([path]);
      const errors: string[] = [];
      expect(
        await reportDryRunPlan({ fs, log: () => {}, error: (line) => errors.push(line) }, plan),
      ).toBe(1);
      expect(errors).toEqual([`WOULD REFUSE: ${path} already exists`]);
    }
  });

  it('leaves a managed file without a marker overwritable, as before', async () => {
    const fs = createFakeFs();
    await fs.writeFile(path, new TextEncoder().encode('anything'));
    expect(await findExisting(fs, [{ path, contents: 'x', managed: true }])).toEqual([]);
  });
});

describe('create-only files', () => {
  const path = '/app/test/support/sign-in.ts';
  const plan = [{ path, contents: 'template', createOnly: true }];

  it('creates an absent file and reports it in both dry run and real write', async () => {
    const fs = createFakeFs();
    const out: string[] = [];
    expect(await findExisting(fs, plan)).toEqual([]);
    expect(
      await reportDryRunPlan({ fs, log: (line) => out.push(line), error: () => {} }, plan),
    ).toBe(0);
    expect(out).toEqual([`would create ${path}`]);
    expect(fs.writes).toEqual([]);
    expect(await writeFiles(fs, plan, { root: '/app' })).toEqual([{ path, outcome: 'created' }]);
    expect(fs.read(path)).toBe('template');
  });

  it('keeps arbitrary existing bytes without reading, writing or refusing the file', async () => {
    const fs = createFakeFs();
    const bytes = new Uint8Array([255, 0, 13, 10, 239, 187, 191]);
    await fs.writeFile(path, bytes);
    const untouched = {
      ...fs,
      readFile: () => Promise.reject(new Error('must not read')),
      writeFile: () => Promise.reject(new Error('must not write')),
      writeRegularFile: () => Promise.reject(new Error('must not replace')),
    };
    const expected = [{ path, outcome: 'unchanged' }];
    expect(await findExisting(untouched, plan)).toEqual([]);
    expect(await classifyFiles(untouched, plan)).toEqual(expected);
    const out: string[] = [];
    const err: string[] = [];
    expect(
      await reportDryRunPlan(
        {
          fs: untouched,
          log: (line) => out.push(line),
          error: (line) => err.push(line),
        },
        plan,
      ),
    ).toBe(0);
    expect(out).toEqual([`unchanged ${path}`]);
    expect(err).toEqual([]);
    expect(await writeFiles(untouched, plan, { root: '/app' })).toEqual(expected);
    expect(await fs.readFile(path)).toEqual(bytes);
    expect(fs.writes).toEqual([path]);
    expect(fs.mkdirs).toEqual([]);
  });

  it('propagates non-missing stat errors at every entry point', async () => {
    const fs = {
      ...createFakeFs({ [path]: 'mine' }),
      stat: () => Promise.reject(new Error('permission denied')),
    };
    await expect(findExisting(fs, plan)).rejects.toThrow('permission denied');
    await expect(classifyFiles(fs, plan)).rejects.toThrow('permission denied');
    await expect(reportDryRunPlan({ fs, log: () => {}, error: () => {} }, plan)).rejects.toThrow(
      'permission denied',
    );
    await expect(writeFiles(fs, plan, { root: '/app' })).rejects.toThrow('permission denied');
    expect(fs.read(path)).toBe('mine');
    expect(fs.writes).toEqual([]);
  });

  it('leaves an existing application-owned link alone without a write refusal', async () => {
    const fs = createFakeFs({ [path]: 'application' });
    const linked = {
      ...fs,
      realPath: () => Promise.resolve('/elsewhere/sign-in.ts'),
    };
    expect(await writeFiles(linked, plan, { root: '/app' })).toEqual([
      { path, outcome: 'unchanged' },
    ]);
    expect(fs.read(path)).toBe('application');
    expect(fs.writes).toEqual([]);
  });

  it.each([false, true])(
    'rolls back only create-only files this batch created (existing=%s)',
    async (existing) => {
      const fs = createFakeFs(existing ? { [path]: 'application\r\n' } : {});
      const removed: string[] = [];
      const failing = {
        ...fs,
        writeFile: (target: string, bytes: Uint8Array) =>
          target === '/app/fail.ts'
            ? Promise.reject(new Error('disk full'))
            : fs.writeFile(target, bytes),
        rm: (target: string) => {
          removed.push(target);
          return fs.rm(target);
        },
      };
      await expect(
        writeFiles(failing, [...plan, { path: '/app/fail.ts', contents: 'fail' }], {
          root: '/app',
        }),
      ).rejects.toThrow('disk full');
      expect(fs.has('/app/fail.ts')).toBe(false);
      expect(fs.has(path)).toBe(existing);
      if (existing) {
        expect(fs.read(path)).toBe('application\r\n');
        expect(fs.writes).not.toContain(path);
        expect(removed).not.toContain(path);
      } else {
        expect(removed).toContain(path);
      }
    },
  );
});

describe('firstDuplicatePath', () => {
  it('reports dry-run create, managed update, unchanged and collision without writes', async () => {
    const fs = createFakeFs({ '/update': 'old', '/same': 'same', '/collision': 'mine' });
    const out: string[] = [];
    const err: string[] = [];
    const deps = {
      fs,
      log: (line: string) => out.push(line),
      error: (line: string) => err.push(line),
    };
    const files = [
      { path: '/new', contents: 'new' },
      { path: '/update', contents: 'next', managed: true },
      { path: '/same', contents: 'same', managed: true },
    ];
    expect(await reportDryRunPlan(deps, files)).toBe(0);
    expect(out).toEqual(['would create /new', 'would update /update', 'unchanged /same']);
    expect(await reportDryRunPlan(deps, [{ path: '/collision', contents: 'next' }])).toBe(1);
    expect(err).toEqual(['WOULD REFUSE: /collision already exists']);
    expect(out).toEqual(['would create /new', 'would update /update', 'unchanged /same']);
    expect(fs.writes).toEqual([]);
    expect(fs.read('/collision')).toBe('mine');
  });
  // The overwrite check probes the filesystem, so it cannot see a path planned
  // twice within one plan — both would be written and the last would win.
  it('finds a path planned twice', () => {
    expect(
      firstDuplicatePath([
        { path: 'deno.json', contents: '{}' },
        { path: 'main.ts', contents: '' },
        { path: 'deno.json', contents: 'overwrites the framework manifest' },
      ]),
    ).toBe('deno.json');
  });

  it('returns the FIRST duplicate when there are several', () => {
    expect(
      firstDuplicatePath([
        { path: 'a', contents: '' },
        { path: 'b', contents: '' },
        { path: 'a', contents: '' },
        { path: 'b', contents: '' },
      ]),
    ).toBe('a');
  });

  it('returns undefined for a distinct plan', () => {
    expect(
      firstDuplicatePath([
        { path: 'deno.json', contents: '' },
        { path: 'main.ts', contents: '' },
      ]),
    ).toBeUndefined();
  });

  it('returns undefined for an empty plan', () => {
    expect(firstDuplicatePath([])).toBeUndefined();
  });
});

describe('joinPath', () => {
  it('joins relative segments', () => {
    expect(joinPath('src', 'services', 'a.ts')).toBe('src/services/a.ts');
  });

  it('preserves a leading slash', () => {
    expect(joinPath('/tmp/app', 'src/a.ts')).toBe('/tmp/app/src/a.ts');
  });

  it('collapses repeated separators', () => {
    expect(joinPath('/tmp//app/', '/src/a.ts')).toBe('/tmp/app/src/a.ts');
  });

  it('ignores empty segments', () => {
    expect(joinPath('', 'src', '', 'a.ts')).toBe('src/a.ts');
  });

  it('returns an empty string for no segments', () => {
    expect(joinPath()).toBe('');
  });
});

describe('resolveDir', () => {
  it('returns the cwd when no --dir was supplied', () => {
    expect(resolveDir('/work')).toBe('/work');
  });

  it('returns the cwd for an empty --dir', () => {
    expect(resolveDir('/work', '')).toBe('/work');
  });

  it('passes an absolute --dir through, normalized', () => {
    expect(resolveDir('/work', '/tmp//sandbox/')).toBe('/tmp/sandbox');
  });

  it('anchors a relative --dir to the cwd', () => {
    // Regression: a relative --dir used to reach `import()` as `/proj/...`,
    // resolving against the filesystem ROOT instead of the cwd.
    expect(resolveDir('/work', 'proj')).toBe('/work/proj');
  });

  // The `/./` used to survive into the resolved path. Nothing failed loudly —
  // every filesystem call honours it — but it reached every path the CLI PRINTS,
  // and `setu adopt` derives its member name from the last segment, so `--dir .`
  // produced a member literally called `.` and a conversion that died on `mkdir
  // apps/.`.
  it('anchors a dot-relative --dir to the cwd, resolving the dots', () => {
    expect(resolveDir('/work', './proj/nested')).toBe('/work/proj/nested');
    expect(resolveDir('/work/svc', '.')).toBe('/work/svc');
    expect(resolveDir('/work/svc', '..')).toBe('/work');
  });

  // What every filesystem does with `/..`: a path cannot climb above the root.
  it('cannot be walked above the filesystem root', () => {
    expect(resolveDir('/work', '../../..')).toBe('/');
  });
});

