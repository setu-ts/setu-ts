import { expect, it } from 'vitest';
import { runCli } from '../../../src/cli.ts';
import { createFakeFs, createRecorder } from '../../fixtures/fake-fs.ts';
import { workspaceProfile } from '../../../src/workspace/runtime-profile.ts';
import { format } from 'prettier';
import { PRETTIER_OPTIONS } from '../../../src/templates/npm-tooling.ts';

it('V13-154 formats workspace package.json with the project formatter inferred parser', async () => {
  const fs = createFakeFs();
  expect(
    await runCli(['new', 'ws', '--workspace'], {
      fs,
      cwd: '/work',
      now: () => 0,
      log: () => {},
      error: () => {},
    }),
  ).toBe(0);
  const source = fs.read('/work/ws/package.json');
  expect(source).toBe(await format(source, { ...PRETTIER_OPTIONS, filepath: 'package.json' }));
});

it.each(['node', 'bun'] as const)(
  'V13-154 renders the root test runner for new and adopted %s workspaces',
  async (runtime) => {
    for (const adopt of [false, true]) {
      const fs = createFakeFs();
      const errors = createRecorder();
      const deps = { fs, cwd: '/work', now: () => 0, log: () => {}, error: errors.sink };
      expect(
        await runCli(
          [
            'new',
            'svc',
            '--runtime',
            runtime,
            ...(adopt ? ['--template', 'rest'] : ['--workspace']),
          ],
          deps,
        ),
        errors.text(),
      ).toBe(0);
      if (adopt) {
        if (runtime === 'bun')
          await fs.writeFile('/work/svc/bun.lock', new TextEncoder().encode('{}\n'));
        expect(await runCli(['adopt', '--dir', '/work/svc'], deps), errors.text()).toBe(0);
      }
      const manifest = JSON.parse(fs.read('/work/svc/package.json'));
      expect(manifest.scripts.test).toBe(`${runtime === 'node' ? 'node' : 'bun'} scripts/test.mjs`);
      const runner = fs.read('/work/svc/scripts/test.mjs');
      expect(runner).toContain('// Generated by `setu new --workspace`.');
      expect(runner).toContain('No members or libraries yet; nothing to test.');
      expect(runner).toContain("process.platform === 'win32'");
      expect(runner).toContain(workspaceProfile(runtime).testAll);
      expect(runner).toContain('workspaces');
      expect(runner).toContain('package.json');
    }
  },
);
