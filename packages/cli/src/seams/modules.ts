/**
 * Feature-module registration renderers.
 *
 * Every module directory has a CLI-managed `index.ts` exporting
 * `register<Pascal>Module(router, services)`, which registers the module's
 * function controllers. In a functional module that is every controller. In a
 * class-based module the class controllers are listed by the module's own
 * `@Module` declaration, so the index registers only its function controllers,
 * the escape hatch `setu g route --module` writes, and re-exports the
 * declaration.
 *
 * @module
 */
import { artifactNames } from '../utils/artifact-path.ts';

import type { DerivedNames } from '../utils/names.ts';
import type { GeneratorMode } from '../utils/generator-mode.ts';
import { seamNames, type SeamArtifacts } from './seam-spec.ts';
import { FUNCTION_CONTROLLER_ARTIFACTS, routeRegistrarSymbol } from './http.ts';

/** Application-level functional module registrar. */
export const REGISTER_MODULES_EXPORT = 'registerModules';

/**
 * Artifact key of a module's request-bound service (M130 §3.4): present for a
 * module whose `<m>.token.ts` exports its token, in a full-stack project.
 */
export const MODULE_SERVICE_ARTIFACTS = 'module-service';

/** The one registrar exported by a functional module index. */
export function registerModuleSymbol(names: DerivedNames): string {
  return `register${names.pascal}Module`;
}

/** A module's request-bound service registration, rendered into its index. */
interface ModuleServiceRegistration {
  readonly token: string;
  readonly factory: string;
  readonly kebab: string;
}

function renderRegistrar(
  symbol: string,
  entries: readonly { readonly symbol: string; readonly from: string }[],
  reExports = '',
  service?: ModuleServiceRegistration,
): string {
  const commonImport =
    service === undefined
      ? "import type { IRouterApi, IServiceRegistry } from '@setu-ts/common';"
      : "import { requestService, type IRouterApi, type IServiceRegistry } from '@setu-ts/common';";
  const serviceImports =
    service === undefined
      ? ''
      : `import { ${service.factory} } from './${service.kebab}.service.ts';\n` +
        `import { ${service.token} } from './${service.kebab}.token.ts';\n`;
  // Without the registry the module's token would be silently unregistered and
  // every page resolving it would fail far from the cause.
  const registration =
    service === undefined
      ? []
      : [
          '  if (services === undefined) {',
          `    throw new Error('${symbol} needs the service registry: call registerModules(app.router, app.services).');`,
          '  }',
          `  services.register(${service.token}, requestService(${service.factory}));`,
        ];
  const calls = entries.map((entry) => `  ${entry.symbol}(router, services);`);
  const body =
    registration.length + calls.length === 0
      ? '  void router;\n  void services;'
      : [...registration, ...(calls.length === 0 ? ['  void router;'] : calls)].join('\n');
  return `/** CLI-owned; regenerated by setu generate module or setu generate … --module <name>. */
${commonImport}
${serviceImports}${entries.map((entry) => `import { ${entry.symbol} } from '${entry.from}';\n`).join('')}${reExports}
/** Registers the feature${service === undefined ? '' : "'s request-bound service and its"} routes. */
export function ${symbol}(router: IRouterApi, services?: IServiceRegistry): void {
${body}
}
`;
}

/**
 * Renders the managed index calling every admitted sibling registrar in order,
 * and registering the module's request-bound service when the scan admitted
 * its token ({@linkcode MODULE_SERVICE_ARTIFACTS}).
 *
 * @param names - The module's derived names
 * @param artifacts - The module's scanned families
 * @returns The contents of `src/modules/<name>/index.ts`
 */
export function renderFunctionalModuleIndex(names: DerivedNames, artifacts: SeamArtifacts): string {
  const entries = seamNames(artifacts, 'controller').map((name) => ({
    symbol: routeRegistrarSymbol(artifactNames(name)),
    from: `./${name}.controller.ts`,
  }));
  const service = seamNames(artifacts, MODULE_SERVICE_ARTIFACTS).includes(names.kebab)
    ? { token: names.screaming, factory: `${names.camel}Service`, kebab: names.kebab }
    : undefined;
  return renderRegistrar(registerModuleSymbol(names), entries, '', service);
}

/**
 * Renders a class-based module's managed index: the declaration re-export and a
 * registrar for the module's function controllers, empty when it has none.
 *
 * @param names - The module's derived names
 * @param artifacts - The module's controller family, as scanned
 * @returns The contents of `src/modules/<name>/index.ts`
 */
export function renderClassModuleIndex(names: DerivedNames, artifacts: SeamArtifacts): string {
  const entries = seamNames(artifacts, FUNCTION_CONTROLLER_ARTIFACTS).map((name) => ({
    symbol: routeRegistrarSymbol(artifactNames(name)),
    from: `./${name}.controller.ts`,
  }));
  return renderRegistrar(
    registerModuleSymbol(names),
    entries,
    `export { ${names.pascal}Module } from './${names.kebab}.module.ts';\n`,
  );
}

/**
 * Renders a module's managed index for the project's generator mode.
 *
 * @param mode - The project's generator mode
 * @param names - The module's derived names
 * @param artifacts - The module's controller family, as scanned
 * @returns The contents of `src/modules/<name>/index.ts`
 */
export function renderModuleIndex(
  mode: GeneratorMode,
  names: DerivedNames,
  artifacts: SeamArtifacts,
): string {
  return mode === 'class-based'
    ? renderClassModuleIndex(names, artifacts)
    : renderFunctionalModuleIndex(names, artifacts);
}

/** Renders the sorted application activation barrel for functional modules. */
export function renderFunctionalModuleBarrel(modules: readonly string[]): string {
  return renderRegistrar(
    REGISTER_MODULES_EXPORT,
    [...new Set(modules)].sort().map((name) => ({
      symbol: registerModuleSymbol(artifactNames(name)),
      from: `./${name}/index.ts`,
    })),
  );
}
