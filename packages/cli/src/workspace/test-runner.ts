/** Renders the npm/Bun workspace test runner owned by the CLI. @module */
import type { GeneratedFile } from '../utils/file-writer.ts';
import type { WorkspaceRuntimeProfile } from './runtime-profile.ts';

/**
 * Renders the empty-workspace check and delegates member execution to the profile.
 *
 * @param profile - The workspace's package-manager commands
 * @returns The generated root test runner
 */
export function workspaceTestRunner(profile: WorkspaceRuntimeProfile): GeneratedFile {
  return {
    path: 'scripts/test.mjs',
    contents: `// Generated by \`setu new --workspace\`. Tests this workspace's members and libraries.
import { spawn } from 'node:child_process';
import { glob, readFile, stat } from 'node:fs/promises';
import { join } from 'node:path';
import process from 'node:process';

const { workspaces = [] } = JSON.parse(await readFile('package.json', 'utf8'));
const patterns = Array.isArray(workspaces) ? workspaces : workspaces.packages;
let hasMembers = false;
for await (const path of glob(patterns)) {
  try {
    if ((await stat(join(path, 'package.json'))).isFile()) {
      hasMembers = true;
      break;
    }
  } catch (cause) {
    if (cause.code !== 'ENOENT' && cause.code !== 'ENOTDIR') throw cause;
  }
}

if (!hasMembers) {
  process.stdout.write('No members or libraries yet; nothing to test.\\n');
} else {
  const testAll = ${JSON.stringify(profile.testAll)};
  const [command, ...args] = testAll.match(/'[^']*'|\\S+/g).map((word) => word.replace(/^'(.*)'$/, '$1'));
  const child = spawn(command, args, { stdio: 'inherit', shell: process.platform === 'win32' });
  child.once('error', (error) => {
    process.stderr.write(error.message + '\\n');
    process.exitCode = 1;
  });
  child.once('close', (code) => {
    process.exitCode = code ?? 1;
  });
}
`,
  };
}
