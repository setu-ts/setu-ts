/**
 * Runs before paint. Storage is untrusted and is only compared against literals.
 * @returns A static inline script; storage errors leave the system preference usable
 */
export function renderThemeScript(): string {
  return `(function () {
  var theme;
  try { theme = localStorage.getItem('${THEME_STORAGE_KEY}'); } catch { /* Storage may be unavailable. */ }
  var dark = theme === 'dark' || (theme !== 'light' && matchMedia('(prefers-color-scheme: dark)').matches);
  document.documentElement.classList.toggle('dark', dark);
  document.documentElement.style.colorScheme = dark ? 'dark' : 'light';
})();`;
}
