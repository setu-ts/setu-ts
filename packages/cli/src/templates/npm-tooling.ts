/**
 * The type-check, lint and format tooling every npm-manifest project carries.
 *
 * A Deno project gets `deno check`, `deno lint` and `deno fmt` from its runtime.
 * A Node, Bun or Workers project gets nothing from its runtime, so before M111d
 * it could not be type-checked, linted or formatted at all — and could not have
 * been type-checked with a bare `tsc` either, since its imports end in `.ts`.
 * One owner here means the three targets cannot disagree about what "clean"
 * means.
 *
 * Two pins are deliberate. TypeScript is held to the 6.0 line because
 * typescript-eslint 8.71 declares `typescript >=4.8.4 <6.1.0`. And the ESLint
 * configuration is the NON-type-aware preset: the type-aware ones need parser
 * project configuration per template, for no rule this project relies on.
 *
 * @module
 */

import type { GeneratedFile } from '../utils/file-writer.ts';

/** The devDependencies the tooling scripts run. */
export const NPM_TOOLING_DEV_DEPENDENCIES: Readonly<Record<string, string>> = {
  '@eslint/js': '^10.0.1',
  eslint: '^10.12.0',
  prettier: '^3.9.10',
  typescript: '~6.0.3',
  'typescript-eslint': '^8.71.1',
};

/** The scripts that run them. */
export const NPM_TOOLING_SCRIPTS: Readonly<Record<string, string>> = {
  check: 'tsc --noEmit && setu check',
  lint: 'eslint .',
  format: 'prettier --write .',
  'format:check': 'prettier --check .',
};

/**
 * The Prettier options a scaffolded `.prettierrc.json` carries, and the ones the
 * CLI formats with when a project has none on disk yet.
 */
export const PRETTIER_OPTIONS: Readonly<Record<string, unknown>> = {
  singleQuote: true,
  printWidth: 100,
  tabWidth: 2,
};

/**
 * Generated output and installed packages: never linted or formatted, since
 * none is source the project owns. `src/gen/` is where a gRPC member's
 * `proto:gen` writes compiler output, which its next run overwrites.
 */
const IGNORED_OUTPUT: readonly string[] = ['node_modules/', 'dist/', '.wrangler/', 'src/gen/'];

/**
 * Renders the ESLint flat configuration.
 *
 * `consistent-type-imports` matches the `verbatimModuleSyntax` the generated
 * `tsconfig.json` sets, and the `^_` argument pattern admits the `_env` and
 * `_devtool` parameters a generated factory declares for its callers' sake.
 *
 * @param generatedOutputDirs - A frontend toolchain's generated directories
 * @returns The file contents
 */
function eslintConfig(generatedOutputDirs: readonly string[]): string {
  const ignores = [...IGNORED_OUTPUT, ...generatedOutputDirs.map((path) => `${path}/`)]
    .map((path) => `'${path}'`)
    .join(', ');
  return `// Generated by setu. ESLint for this project's TypeScript sources.
import js from '@eslint/js';
import { defineConfig } from 'eslint/config';
import tseslint from 'typescript-eslint';

export default defineConfig(
  { ignores: [${ignores}] },
  js.configs.recommended,
  tseslint.configs.recommended,
  {
    files: ['**/*.ts', '**/*.tsx'],
    rules: {
      '@typescript-eslint/consistent-type-imports': 'error',
      '@typescript-eslint/no-explicit-any': 'error',
      '@typescript-eslint/no-unused-vars': ['error', { argsIgnorePattern: '^_' }],
    },
  },
);
`;
}

/**
 * The tooling's configuration files.
 *
 * @param generatedOutputDirs - A frontend toolchain's generated directories
 * @returns The files to add to the project
 */
export function npmToolingFiles(generatedOutputDirs: readonly string[]): readonly GeneratedFile[] {
  const ignored = [
    ...IGNORED_OUTPUT,
    ...generatedOutputDirs.map((path) => `${path}/`),
    'package-lock.json',
    'bun.lock',
  ];
  return [
    { path: 'eslint.config.js', contents: eslintConfig(generatedOutputDirs) },
    {
      path: '.prettierrc.json',
      contents: `${JSON.stringify(PRETTIER_OPTIONS, null, 2)}\n`,
    },
    { path: '.prettierignore', contents: `${ignored.join('\n')}\n` },
  ];
}
