/**
 * {@linkcode grpcClient} — the typed way to call another service (M139b §3.12).
 *
 * @module
 */
import type { DescService } from '@bufbuild/protobuf';
import type { Client } from '@connectrpc/connect';
import { CAPABILITIES } from '@setu-ts/common';
import type {
  GrpcClientOptions,
  IGrpcService,
  InjectionToken,
  IServiceRegistry,
  ModuleFactoryProvider,
} from '@setu-ts/common';

import { targetBase, validateClientOptions } from './grpc-client.ts';

/**
 * A Connect client for a service another process serves, through the
 * registered `GrpcPlugin`.
 *
 * `target` is a service name resolved through service discovery on every call
 * (the client reports each outcome back, so an instance that refuses
 * connections is ejected), or an absolute `http(s)://` URL. Connections are
 * shared per origin and closed with the application, calls carry the active
 * span's `traceparent`, and each has a deadline (5 s unless configured). The
 * same arguments return the same client, so calling this per request is a
 * lookup.
 *
 * A failed call rejects with Connect's `ConnectError`: `Unavailable` when no
 * instance is known or the connection fails, `DeadlineExceeded` past the
 * deadline, and the server's own code otherwise.
 *
 * @example
 * ```typescript
 * // setu.config.ts: GrpcPlugin({ serve: false, clients: { billing: { basePath: '/grpc' } } })
 * const billing = grpcClient(ctx.services, BillingService, 'billing');
 * const quote = await billing.quote({ items });
 * ```
 *
 * @param services - The application's service registry
 * @param definition - The service descriptor generated by Protobuf-ES
 * @param target - A service name known to discovery, or an absolute URL
 * @param options - Overrides for this client
 * @returns The typed client
 * @throws {TypeError} When the registered gRPC service cannot make clients, an
 *   option is out of range, or `target` is a name and no discovery is registered
 * @since 0.13.0
 */
export function grpcClient<TService extends DescService>(
  services: IServiceRegistry,
  definition: TService,
  target: string,
  options?: GrpcClientOptions,
): Client<TService> {
  return clientOf(services.get<IGrpcService>(CAPABILITIES.GRPC), definition, target, options);
}

/**
 * The same client as {@linkcode grpcClient}, as a DI provider (M139b §3.13):
 * an entry for `@Module({ providers })` that registers the client under
 * `provide`, so a class takes it with `@Inject(provide)`. It resolves
 * `CAPABILITIES.GRPC` and asks it for the client — the path `grpcClient()`
 * takes — as a singleton.
 *
 * The options and target are checked here, when the module is declared,
 * rather than on the first injection.
 *
 * @example
 * ```typescript
 * // `@Inject` names string tokens; `createToken()` suits `container.resolve()`.
 * export const BILLING = 'billing.client';
 *
 * @Module({
 *   controllers: [OrdersController],
 *   providers: [OrdersService, grpcClientProvider(BILLING, BillingService, 'billing')],
 * })
 * export class OrdersModule {}
 *
 * @Injectable()
 * @Inject(BILLING)
 * export class OrdersService {
 *   constructor(private readonly billing: Client<typeof BillingService>) {}
 * }
 * ```
 *
 * @param provide - The token the client is registered under
 * @param definition - The service descriptor generated by Protobuf-ES
 * @param target - A service name known to discovery, or an absolute URL
 * @param options - Overrides for this client
 * @returns The provider entry
 * @throws {TypeError} When an option is out of range, or the target is empty or
 *   a URL that is not `http(s)`
 * @since 0.13.0
 */
export function grpcClientProvider<TService extends DescService>(
  provide: string | InjectionToken<Client<TService>>,
  definition: TService,
  target: string,
  options?: GrpcClientOptions,
): ModuleFactoryProvider<Client<TService>> {
  validateClientOptions(options ?? {}, 'grpcClientProvider');
  targetBase(target);
  return {
    provide,
    useFactory: (grpc: IGrpcService) => clientOf(grpc, definition, target, options),
    inject: [CAPABILITIES.GRPC],
    scope: 'singleton',
  };
}

/** Asks a gRPC service for a client: the one path both helpers take. */
function clientOf<TService extends DescService>(
  grpc: IGrpcService,
  definition: TService,
  target: string,
  options: GrpcClientOptions | undefined,
): Client<TService> {
  if (typeof grpc.client !== 'function') {
    throw new TypeError(
      'grpcClient: the registered gRPC service has no client(); register GrpcPlugin from @setu-ts/grpc-plugin',
    );
  }
  return grpc.client(definition, target, options) as Client<TService>;
}
