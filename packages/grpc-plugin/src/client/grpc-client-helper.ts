/**
 * {@linkcode grpcClient} — the typed way to call another service (M139b §3.12).
 *
 * @module
 */
import type { DescService } from '@bufbuild/protobuf';
import type { Client } from '@connectrpc/connect';
import { CAPABILITIES } from '@setu-ts/common';
import type { GrpcClientOptions, IGrpcService, IServiceRegistry } from '@setu-ts/common';

/**
 * A Connect client for a service another process serves, through the
 * registered `GrpcPlugin`.
 *
 * `target` is a service name resolved through service discovery on every call
 * (the client reports each outcome back, so an instance that refuses
 * connections is ejected), or an absolute `http(s)://` URL. Connections are
 * shared per origin and closed with the application, calls carry the active
 * span's `traceparent`, and each has a deadline (5 s unless configured). The
 * same arguments return the same client, so calling this per request is a
 * lookup.
 *
 * A failed call rejects with Connect's `ConnectError`: `Unavailable` when no
 * instance is known or the connection fails, `DeadlineExceeded` past the
 * deadline, and the server's own code otherwise.
 *
 * @example
 * ```typescript
 * // setu.config.ts: GrpcPlugin({ serve: false, clients: { billing: { basePath: '/grpc' } } })
 * const billing = grpcClient(ctx.services, BillingService, 'billing');
 * const quote = await billing.quote({ items });
 * ```
 *
 * @param services - The application's service registry
 * @param definition - The service descriptor generated by Protobuf-ES
 * @param target - A service name known to discovery, or an absolute URL
 * @param options - Overrides for this client
 * @returns The typed client
 * @throws {TypeError} When the registered gRPC service cannot make clients, an
 *   option is out of range, or `target` is a name and no discovery is registered
 * @since 0.13.0
 */
export function grpcClient<TService extends DescService>(
  services: IServiceRegistry,
  definition: TService,
  target: string,
  options?: GrpcClientOptions,
): Client<TService> {
  const grpc = services.get<IGrpcService>(CAPABILITIES.GRPC);
  if (typeof grpc.client !== 'function') {
    throw new TypeError(
      'grpcClient: the registered gRPC service has no client(); register GrpcPlugin from @setu-ts/grpc-plugin',
    );
  }
  return grpc.client(definition, target, options) as Client<TService>;
}
